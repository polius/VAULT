// Regenerates the third-party files in src/js/vendor/ from pinned sources.
//
//   npm run vendor          rewrite the vendored files
//   npm run vendor:check    fail if a vendored file differs from its source (CI)
//
// Every source is pinned (npm version via package-lock, URLs by commit/path and
// SHA-256), so the output is byte-for-byte reproducible.
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';

const ROOT = new URL('../', import.meta.url);
const OUT = new URL('src/js/vendor/', ROOT);
const CHECK = process.argv.includes('--check');

const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');

async function download(url, expectedSha) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  const buf = Buffer.from(await res.arrayBuffer());
  const got = sha256(buf);
  if (got !== expectedSha) throw new Error(`${url}: sha256 ${got} != pinned ${expectedSha}`);
  return buf.toString('utf8');
}

// hash-wasm ships Argon2 as UMD only. Running it with a local CommonJS-shaped
// `module` turns it into a side-effect-free ES module (no globals, no eval).
async function argon2() {
  const pkg = JSON.parse(await readFile(new URL('node_modules/hash-wasm/package.json', ROOT), 'utf8'));
  const umd = await readFile(new URL('node_modules/hash-wasm/dist/argon2.umd.min.js', ROOT), 'utf8');
  return [
    `// hash-wasm ${pkg.version} (MIT, Dani Biró) dist/argon2.umd.min.js, wrapped as an ES module.`,
    '// Generated by scripts/vendor.mjs. Do not edit.',
    'const module = { exports: {} };',
    'const exports = module.exports;',
    umd.trim(),
    'export const { argon2id } = module.exports;',
    '',
  ].join('\n');
}

async function effWordlist() {
  const txt = await download(
    'https://www.eff.org/files/2016/07/18/eff_large_wordlist.txt',
    'addd35536511597a02fa0a9ff1e5284677b8883b83e986e43f15a3db996b903e',
  );
  const words = txt
    .trim()
    .split('\n')
    .map((l) => l.split('\t')[1].trim());
  if (words.length !== 7776) throw new Error(`EFF list has ${words.length} words, expected 7776`);
  return [
    '// EFF Large Wordlist for Passphrases (7,776 words), https://www.eff.org/dice',
    '// CC BY 3.0 US, Electronic Frontier Foundation. Generated by scripts/vendor.mjs. Do not edit.',
    `export const WORDS = ${JSON.stringify(words.join(' '))}.split(' ');`,
    '',
  ].join('\n');
}

async function commonPasswords() {
  const txt = await download(
    'https://raw.githubusercontent.com/danielmiessler/SecLists/913b327317496d062bcc7cace524aaad8a693be2/Passwords/Common-Credentials/10k-most-common.txt',
    '68782d6a4a19a4768d5f15dd66bd534e7a33055cc755411e33f16d18c50fdcce',
  );
  const list = [
    ...new Set(
      txt
        .split('\n')
        .map((l) => l.trim().toLowerCase())
        .filter(Boolean),
    ),
  ];
  return [
    '// SecLists 10k-most-common.txt (MIT, Daniel Miessler et al.), lower-cased and de-duplicated.',
    '// Generated by scripts/vendor.mjs. Do not edit.',
    `export const COMMON = ${JSON.stringify(list.join('\n'))}.split('\\n');`,
    '',
  ].join('\n');
}

const targets = { 'argon2.js': argon2, 'eff-wordlist.js': effWordlist, 'common-passwords.js': commonPasswords };

let stale = 0;
for (const [name, build] of Object.entries(targets)) {
  const content = await build();
  const url = new URL(name, OUT);
  if (CHECK) {
    const current = await readFile(url, 'utf8').catch(() => '');
    if (current !== content) {
      console.error(`stale: src/js/vendor/${name}`);
      stale++;
    } else console.log(`ok: src/js/vendor/${name}`);
  } else {
    await writeFile(url, content);
    console.log(`wrote src/js/vendor/${name} (${content.length} bytes)`);
  }
}
if (stale) process.exit(1);
